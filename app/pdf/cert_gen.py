"""
VouchPay — PDF Certificate Generator
Timestamped, SHA-256-verified verification certificates.
"""

import os
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib.colors import HexColor
from reportlab.pdfgen import canvas as pdf_canvas
from app.schemas import VerificationRecord


class CertificateGenerator:
    """Produces downloadable PDF verification certificates."""

    STATUS_COLORS = {
        "CONFIRMED": "#22c55e",
        "SUSPICIOUS": "#f59e0b",
        "DISPUTED": "#ef4444",
        "PENDING": "#6b7280",
    }

    def generate(self, record: VerificationRecord, tx_id: str) -> str:
        out_dir = os.path.join("static", "uploads", tx_id)
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, f"VouchPay_Certificate_{tx_id}.pdf")

        c = pdf_canvas.Canvas(path, pagesize=A4)
        w, h = A4
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S IST")

        # ---- header band ----
        c.setFillColor(HexColor("#1a1a2e"))
        c.rect(0, h - 120, w, 120, fill=True, stroke=False)

        c.setFillColor(HexColor("#00d4ff"))
        c.setFont("Helvetica-Bold", 28)
        c.drawCentredString(w / 2, h - 55, "VouchPay")

        c.setFillColor(HexColor("#ffffff"))
        c.setFont("Helvetica", 12)
        c.drawCentredString(w / 2, h - 80, "Payment Verification Certificate")
        c.setFont("Helvetica", 9)
        c.drawCentredString(w / 2, h - 100, f"Generated: {now_str}")

        # ---- status badge ----
        y = h - 170
        badge = self.STATUS_COLORS.get(record.status, "#6b7280")
        c.setFillColor(HexColor(badge))
        c.roundRect(w / 2 - 80, y - 10, 160, 35, 8, fill=True, stroke=False)
        c.setFillColor(HexColor("#ffffff"))
        c.setFont("Helvetica-Bold", 16)
        c.drawCentredString(w / 2, y + 2, record.status)

        # ---- trust score ----
        y -= 60
        c.setFillColor(HexColor("#1a1a2e"))
        c.setFont("Helvetica-Bold", 14)
        c.drawString(60, y, "Trust Score")
        sc = (
            "#22c55e" if record.trust_score >= 80
            else "#f59e0b" if record.trust_score >= 50
            else "#ef4444"
        )
        c.setFillColor(HexColor(sc))
        c.setFont("Helvetica-Bold", 36)
        c.drawString(200, y - 8, f"{record.trust_score} / 100")

        # ---- transaction details ----
        y -= 70
        self._section(c, "Transaction Details", 60, y, w)
        y -= 25
        rows = [
            ("Transaction ID", tx_id),
            ("Amount", f"Rs.{record.extraction.amount}" if record.extraction.amount else "N/A"),
            ("UTR Number", record.extraction.utr or "N/A"),
            ("Date", record.extraction.receipt_date or "N/A"),
            ("Time", record.extraction.receipt_time or "N/A"),
            ("Payment App", record.extraction.app_name or "N/A"),
        ]
        for label, val in rows:
            c.setFont("Helvetica", 11)
            c.setFillColor(HexColor("#6b7280"))
            c.drawString(80, y, f"{label}:")
            c.setFillColor(HexColor("#1a1a2e"))
            c.drawString(220, y, str(val))
            y -= 20

        # ---- forensic summary ----
        y -= 15
        self._section(c, "Forensic Analysis", 60, y, w)
        y -= 25
        f_rows = [
            ("ELA Tamper Score", f"{record.forensics.tamper_score}%"),
            ("SHA-256", record.forensics.image_sha256[:40] + "..."),
            ("EXIF Flags", ", ".join(record.forensics.exif_flags) or "None"),
        ]
        for label, val in f_rows:
            c.setFont("Helvetica", 11)
            c.setFillColor(HexColor("#6b7280"))
            c.drawString(80, y, f"{label}:")
            c.setFillColor(HexColor("#1a1a2e"))
            c.drawString(220, y, str(val))
            y -= 20

        # ---- flags ----
        if record.rule_flags:
            y -= 15
            self._section(c, "Flags Raised", 60, y, w)
            y -= 25
            c.setFont("Helvetica", 10)
            c.setFillColor(HexColor("#ef4444"))
            for flag in record.rule_flags[:8]:
                c.drawString(80, y, f">> {flag}")
                y -= 16

        # ---- footer ----
        c.setFillColor(HexColor("#9ca3af"))
        c.setFont("Helvetica", 8)
        c.drawCentredString(w / 2, 40, f"Generated by VouchPay on {now_str}")
        c.drawCentredString(w / 2, 28, f"SHA-256: {record.forensics.image_sha256}")
        c.drawCentredString(w / 2, 16, "This document is for verification purposes only.")

        c.save()
        return path

    @staticmethod
    def _section(c, title: str, x: float, y: float, w: float):
        c.setFillColor(HexColor("#1a1a2e"))
        c.setFont("Helvetica-Bold", 14)
        c.drawString(x, y, title)
        c.setStrokeColor(HexColor("#e5e7eb"))
        c.line(x, y - 5, w - 60, y - 5)
